"""Default development and optional browser hash locks remain compatible."""

from __future__ import annotations

import tomllib
from pathlib import Path

import pytest
from packaging.requirements import Requirement

from scripts import validate_dependency_lock as locks

ROOT = Path(__file__).resolve().parents[1]


def _pin(name: str, version: str, *, hashed: bool = True) -> str:
    result = f"{name}=={version}\n"
    return result + ("    --hash=sha256:" + "a" * 64 + "\n" if hashed else "")


@pytest.fixture
def profiles(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    header = "# This file is autogenerated by pip-compile\n"
    (tmp_path / "requirements-dev.in").write_text("pytest>=8,<10\n")
    (tmp_path / "requirements-dev.txt").write_text(
        header + _pin("pytest", "9.1.1") + _pin("typing-extensions", "4.16.0")
    )
    (tmp_path / "requirements-browser.in").write_text(
        "playwright>=1.64.1,<2\npyee>=13,<14\n"
    )
    browser = tmp_path / "requirements-browser.txt"
    browser.write_text(header + _pin("playwright", "1.64.1") + _pin("pyee", "13.0.1")
                       + _pin("greenlet", "3.5.6") + _pin("typing_extensions", "4.16.0"))
    return tmp_path, browser


def test_compatible_profiles_and_original_validate_api_pass(profiles):
    root, _ = profiles
    assert locks.validate(root / "requirements-dev.in", root / "requirements-dev.txt") == []
    assert locks.main() == 0


@pytest.mark.parametrize("mutation", ["missing_hash", "missing_direct", "bad_version", "header"])
def test_canonical_main_validates_browser_profile(profiles, capsys, mutation):
    _, browser = profiles
    text = browser.read_text()
    if mutation == "missing_hash":
        text = text.replace(_pin("pyee", "13.0.1"), _pin("pyee", "13.0.1", hashed=False))
    elif mutation == "missing_direct":
        text = text.replace(_pin("pyee", "13.0.1"), "")
    elif mutation == "bad_version":
        text = text.replace("pyee==13.0.1", "pyee==14.0.0")
    else:
        text = text.replace("autogenerated by pip-compile", "not a generated lock")
    browser.write_text(text)
    assert locks.main() == 1
    assert "requirements-browser.txt" in capsys.readouterr().err


def test_shared_dependency_aliases_cannot_have_conflicting_exact_pins(profiles, capsys):
    _, browser = profiles
    browser.write_text(browser.read_text().replace("typing_extensions==4.16.0", "typing_extensions==4.17.0"))
    assert locks.main() == 1
    errors = capsys.readouterr().err
    assert "typing-extensions" in errors
    assert "conflicting" in errors
    assert "4.16.0" in errors and "4.17.0" in errors


def test_missing_optional_profile_file_fails_canonical_validation(profiles, capsys):
    _, browser = profiles
    browser.unlink()
    assert locks.main() == 1
    assert "requirements-browser.txt" in capsys.readouterr().err


def test_shipped_profiles_keep_browser_tools_optional_and_python_compatible():
    config = tomllib.loads((ROOT / "pyproject.toml").read_text())
    extras = config["project"]["optional-dependencies"]
    inputs = {
        Requirement(line).name.lower(): str(Requirement(line).specifier)
        for line in (ROOT / "requirements-dev.in").read_text().splitlines()
        if line.strip() and not line.startswith("#")
    }
    development = {Requirement(value).name.lower(): str(Requirement(value).specifier)
                   for value in extras["dev"]}
    browser = {Requirement(value).name.lower(): str(Requirement(value).specifier)
               for value in extras["render"]}
    browser_inputs = {
        Requirement(line).name.lower(): str(Requirement(line).specifier)
        for line in (ROOT / "requirements-browser.in").read_text().splitlines()
    }
    assert development == inputs
    assert not {"playwright", "pyee", "greenlet"} & inputs.keys()
    assert not {"playwright", "pyee", "greenlet"} & locks._parse_lock(
        (ROOT / "requirements-dev.txt").read_text()
    )[0].keys()
    assert browser == {"playwright": "<2,>=1.64.1", "pyee": "<14,>=13"}
    assert browser == browser_inputs
    shipped = config["tool"]["setuptools"]["data-files"]["share/world-class-seo"]
    assert {"requirements-browser.in", "requirements-browser.txt"} <= set(shipped)
    assert len(shipped) == len(set(shipped))
