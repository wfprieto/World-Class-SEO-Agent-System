class GoodAdapter:
    def fetch(self, **kwargs):
        return AdapterResult(
            source="fixture", status="ok", data={"ok": True}, warnings=[]
        )


class LeakyAdapter:
    def fetch(self, **kwargs):
        raise RuntimeError(
            "provider failed with " + "sk-" + "proj-" + "abcdefghijklmnopqrstuvwxyz"
        )


def _repo(tmp_path: Path) -> Path:
    (tmp_path / "seoctl").mkdir()
    (tmp_path / "skills").mkdir()
    (tmp_path / "pyproject.toml").write_text(
        '[project]\nname="world-class-seo-agent-system"\nversion="1.7.0"\n'
        'dependencies=[\n"tenacity>=8.2.0",\n]\n',
        encoding="utf-8",
    )
    (tmp_path / "requirements-dev.txt").write_text(
        "# This file is autogenerated by pip-compile\ntenacity==9.1.4\n",
        encoding="utf-8",
    )
    (tmp_path / "seoctl/command-registry.json").write_text(
        json.dumps({"commands": [{"id": "x"}]}), encoding="utf-8"
    )
    (tmp_path / "skills/skill-catalog.json").write_text(
        json.dumps(
            {"categories": [{"skills": [f"s{i}" for i in range(84)]}]}
        ),
        encoding="utf-8",
    )
    (tmp_path / "module.py").write_text("VALUE = 1\n", encoding="utf-8")
    return tmp_path


def test_secret_scanner_detects_real_secret_and_allows_placeholders(tmp_path: Path):
    token = "sk-" + "proj-" + "abcdefghijklmnopqrstuvwxyz"
    (tmp_path / "bad.env").write_text(
        f'OPENAI_API_KEY="{token}"\n', encoding="utf-8"
    )
    assert scan(tmp_path)
    (tmp_path / "bad.env").write_text(
        'OPENAI_API_KEY="your_placeholder_key"\n', encoding="utf-8"
    )
    assert scan(tmp_path) == []


def test_telemetry_redacts_nested_secret_values():
    trace = OperationTelemetry("provider")
    trace.request_count = 1
    payload = trace.finish(
        status="OK",
        metadata={"authorization": "Bearer secret", "nested": {"api_key": "x"}},
    )
    assert payload["metadata"]["authorization"] == "[REDACTED]"
    assert payload["metadata"]["nested"]["api_key"] == "[REDACTED]"
    assert payload["duration_ms"] >= 0
    assert redact("sk-" + "proj-" + "abcdefghijklmnopqrstuvwxyz") == "[REDACTED]"


def test_dispatch_telemetry_is_present_and_error_secrets_are_sanitized():
    dispatcher = ToolDispatcher({"good": GoodAdapter(), "bad": LeakyAdapter()})
    good = asyncio.run(dispatcher.dispatch(ToolRequest("good", {})))
    assert good.status == "ok"
    bad = asyncio.run(dispatcher.dispatch(ToolRequest("bad", {})))
    assert "sk-proj" not in (bad.sanitized_error or "")
    events = dispatcher.telemetry_snapshot()
    assert events[0]["request_count"] == 1 and events[0]["status"] == "OK"
    assert events[1]["status"] == "FAILED"


def test_sbom_and_release_manifest_validate_and_detect_tampering(tmp_path: Path):
    root = _repo(tmp_path)
    sbom_payload = build_sbom(root)
    assert sbom_payload["components"][0]["version"] == "9.1.4"
    assert "NOT_INSTALLED" not in json.dumps(sbom_payload)
    sbom = root / "sbom.json"
    sbom.write_text(json.dumps(sbom_payload), encoding="utf-8")
    manifest_payload = build_manifest(root, sbom_path=sbom)
    manifest = root / "manifest.json"
    manifest.write_text(json.dumps(manifest_payload), encoding="utf-8")
    assert validate(root, manifest, sbom) == []
    (root / "module.py").write_text("VALUE = 2\n", encoding="utf-8")
    assert any("hash mismatch" in item for item in validate(root, manifest, sbom))


def test_sbom_models_unresolved_optional_dependencies_without_fake_versions(
    tmp_path: Path,
):
    root = _repo(tmp_path)
    pyproject = root / "pyproject.toml"
    pyproject.write_text(
        pyproject.read_text(encoding="utf-8")
        + '\n[project.optional-dependencies]\nrender=["playwright>=1.49,<2"]\n',
        encoding="utf-8",
    )

    payload = build_sbom(root)
    optional = next(row for row in payload["components"] if row["name"] == "playwright")

    assert "version" not in optional
    assert optional["scope"] == "optional"
    assert {row["name"]: row["value"] for row in optional["properties"]}[
        "wcseo:resolution"
    ] == "DECLARED_OPTIONAL_UNRESOLVED"


def test_performance_budgets_are_bounded():
    payload = run_benchmarks(iterations=3)
    assert payload["status"] == "PASS", json.dumps(payload, sort_keys=True)
    assert all(
        row["max_ms"] <= row["budget_ms"] for row in payload["results"].values()
    ), json.dumps(payload, sort_keys=True)


@pytest.mark.parametrize(
    ("case", "status"),
    [
        ("command_registry", "FAIL"),
        ("skill_index_render", "FAIL"),
        ("prompt_manifest", "FAIL"),
        ("command_registry", "PASS"),
        ("skill_index_render", "PASS"),
        ("prompt_manifest", "PASS"),
        pytest.param(None, "PASS", id="ordinary-pass"),
    ],
)
def test_performance_failure_exposes_full_payload(
    monkeypatch: pytest.MonkeyPatch, case: str | None, status: str
) -> None:
    """Synthetic packets test both real assertion paths, not runtime performance."""
    payload: dict[str, object] = {
        "status": status,
        "iterations": 3,
        "results": {
            name: {
                "median_ms": 1.0,
                "max_ms": 251.0 if name == case else 1.0,
                "budget_ms": 250.0,
                "passed": name != case,
            }
            for name in ("command_registry", "skill_index_render", "prompt_manifest")
        },
    }
    iterations_seen: list[int] = []

    def synthetic_benchmark(*, iterations: int) -> dict[str, object]:
        iterations_seen.append(iterations)
        return payload

    monkeypatch.setitem(globals(), "run_benchmarks", synthetic_benchmark)
    if case is None:
        assert test_performance_budgets_are_bounded() is None
    else:
        with pytest.raises(AssertionError) as failure:
            test_performance_budgets_are_bounded()
        assert json.dumps(payload, sort_keys=True) in str(failure.value)
    assert iterations_seen == [3]


def test_measure_keeps_first_slow_sample_and_exact_iterations(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """The real sampler retains its first slow call; only its clock is synthetic."""
    ticks = iter((0.0, 0.251, 1.0, 1.001, 2.0, 2.001))
    monkeypatch.setattr(
        performance_benchmarks, "time", SimpleNamespace(perf_counter=lambda: next(ticks))
    )
    calls: list[int] = []

    def operation() -> None:
        calls.append(len(calls))

    metrics = performance_benchmarks._measure(operation, iterations=3)

    assert metrics == {"median_ms": 1.0, "max_ms": 251.0}
    assert calls == [0, 1, 2]
    with pytest.raises(StopIteration):
        next(ticks)


@pytest.mark.parametrize("case", ("command_registry", "skill_index_render", "prompt_manifest"))
@pytest.mark.parametrize("maximum_ms", (250.0, 250.001))
def test_performance_maximum_is_inclusive_and_aggregated(
    monkeypatch: pytest.MonkeyPatch, case: str, maximum_ms: float,
) -> None:
    """Real run/sampler/metadata logic; finite fake ticks prove policy, not speed."""
    cases = ("command_registry", "skill_index_render", "prompt_manifest")
    samples = [
        maximum_ms if name == case and iteration == 0 else 1.0
        for name in cases
        for iteration in range(3)
    ]
    ticks = iter(
        tick
        for index, duration_ms in enumerate(samples)
        for tick in (float(index), index + duration_ms / 1000)
    )
    monkeypatch.setattr(
        performance_benchmarks, "time", SimpleNamespace(perf_counter=lambda: next(ticks))
    )

    payload = performance_benchmarks.run(iterations=3)

    assert payload["iterations"] == 3
    assert set(payload["results"]) == set(cases)
    for name, row in payload["results"].items():
        expected_maximum = maximum_ms if name == case else 1.0
        assert row["median_ms"] == 1.0
        assert row["max_ms"] == expected_maximum
        assert row["budget_ms"] == 250.0
        assert row["passed"] is (expected_maximum <= 250.0)
    assert payload["status"] == ("PASS" if maximum_ms <= 250.0 else "FAIL")
    with pytest.raises(StopIteration):
        next(ticks)


